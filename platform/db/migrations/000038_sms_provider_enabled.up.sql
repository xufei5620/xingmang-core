-- XM-SMS0：供应商的启用开关搬进数据库。
--
-- 原先是 XM_SMS_PROVIDERS 环境变量（照抄了 XM_CARDS_ACCOUNTS 的做法）。
-- 产品负责人 2026-09-05 指出这不对，而他是对的：**「启用哪几家」是运营会调
-- 的开关，不是部署形态**。要登服务器改文件再重启才能开关一家供应商，
-- 实际上就是没人会去开关它。
--
-- 而且它本来也不该是一份「清单」：代码里只支持两家，一个数据库里写着
-- 「第三家」的行没有任何代码支撑。所以正确的形状是两家各自一个布尔开关，
-- 而不是一串名字。
--
-- **XM_SMS_MODE 保留在环境变量里**，那是另一类：它决定这个进程打真实供应商
-- 还是打内存替身。做成后台可改意味着一次误操作能让开发环境开始真买号，
-- 或者让生产悄悄切到替身而页面看起来一切正常。环境变量按部署固定，点不错。
ALTER TABLE sms.provider_status
    ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT FALSE;

-- 默认 FALSE：**新装环境两家都是关的**。
--
-- 这是唯一正确的默认。一个「装好就自动启用」的供应商，会在有人还没来得及
-- 填密钥、也没来得及想清楚要不要用它的时候，就出现在买号页的可选项里。
-- 开启是一次显式动作，而且要留痕（走 Action，进审计）。
