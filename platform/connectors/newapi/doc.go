// Package newapi 定义 NewAPI 的只读接入契约（规格 §8.4 Foundation-A 只读范围）。
//
// 本包**只声明契约与提供 Fake**，不含任何真实网络/数据库实现——真实实现是
// XM-0038。任何实现（Fake 或真实）都必须通过 contracttest 套件才算合规。
//
// 铁律：
//   - ReadClient 接口**只有读方法**。写范围（Token 管理、渠道启停、模型配置、
//     有限用户管理——规格 §8.4「后续写范围」）在 Foundation-B 后另立接口，
//     不得往本接口上加方法（ADR-018 闸 4）；
//   - 每个返回值都带 ObservedAt 与 Watermark（规格 §9.1：禁止裸数字）；
//   - 金额一律整数最小货币单位 + Currency，禁止 float（规格 §5.9）；
//   - 错误率同样禁 float，用 ppm 整数表达（见 ChannelStatus.ErrorRatePPM）。
//
// # 契约边界：什么不在这里
//
// 产品负责人的 UI 原型里，NewAPI 平台页除了渠道状态之外还要显示四类东西：
//
//	联系人、充值成本率、接入平台标签、上游账号凭据到期日
//
// **这四类都不进本契约**，因为它们不是 NewAPI 的 API 能回答的问题——
// 它们是平台自己对供应商的经营登记，属于**平台经营登记簿**（supplier ledger），
// 由后续的 XM-0037 单独设计（等 UI 定稿）。逐条说清为什么：
//
//   - **联系人**：NewAPI 里没有「这个上游供应商的对接人是谁」这个概念。
//     它是我们自己记下来的联络信息，只存在于我们的经营活动里。
//   - **充值成本率**：容易与规格 §9.2 的「充值倍率」混淆，但两者是不同的对象。
//     充值倍率是 NewAPI 渠道配置里的一个**字段**，读得到；充值成本率是
//     「我们花多少钱买到这些额度」，那是采购合同派生的**经营数字**，
//     NewAPI 完全不知道我们付了多少钱。
//   - **接入平台标签**：我们给上游打的分类标签，上游不持有它。
//   - **上游账号凭据到期日**：凭据元数据。凭据只经 CredentialRef
//     （ADR-014、规格 §8.4 的 Connector → CredentialRef → SecretProvider →
//     只读 DSN 链路），本契约连凭据本身都读不到，更不该去替它记到期日。
//
// 底层依据是 ADR-011 第 4 条：控制平台**不拥有第三方业务数据的最终真相**。
// 把登记簿数据混进只读契约，等于让 `newapi.read.v1` 同时承担两种角色——
// 一半是上游的投影（上游改了我们跟着改），一半是我们自己的账本（我们说了算）。
// 这两半的变更节奏、可信度与冻结条件完全不同，混在一个契约里，第一次上游
// 改字段时就会分不清哪些该跟、哪些不该跟。
//
// 分开还有一个更实际的好处：登记簿是**可写**的（有人要维护联系人），
// 而本包是只读契约。让它们共处一个包，ADR-018 闸 4「Connector 包内无写路径」
// 就只能靠评审时有人记得，而不是靠接口形状本身。
//
// 详见 contracts/connectors/newapi.read.v1.md 的「契约里没有什么」一节。
