// Package integration 实现「接口与自动化」（`/ext/integration`）的两张登记簿：
// API 调用方与自动化规则（ADMIN-IA §5.4.1，2026-09-08 产品负责人裁定）。
//
// 两条必须一直成立的性质，它们是这个包存在的前提，不是附带说明：
//
//  1. **调用方登记簿不是授权面。** 登记一行不发凭据、不授予权限、不设配额；
//     停用一行不会让任何请求被拒绝。授权仍然完整地由 Keycloak Realm 角色
//     （oidcauth.DefaultRoleScopeMap）与员工账号角色决定。登记簿与真实授权
//     之间的差异靠**对账**发现——ListAPIClients 同时给出登记簿与
//     action_run 里实际观测到的调用方，两侧对不上就是有问题，而不是靠假装
//     两侧一致。
//
//  2. **规则登记簿没有执行器。** 本包不 import 任何执行路径，也没有任何
//     调用方会拿本包的规则去触发 Action。自动触发会绕开人工审批那道闸
//     （宪法 9 条：L2 及以上必须审批，而机器凑不出审批人）；要不要让规则
//     引擎真执行、能执行到哪个风险等级，是一件单独要裁定的事，不在本包
//     范围内。TestAutomationRulesNeverExecute 机械地守住这一条。
//
// 写路径一律走 Action（宪法 2 条），读路径由 httpapi 的两个只读端点承担。
