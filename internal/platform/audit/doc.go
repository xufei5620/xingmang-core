// Package audit 实现规格 §4.4 的审计模型：完整字段事件、防篡改哈希链、
// 周期 Chain Root 与独立密钥签名。
//
// 铁律：
//   - 审计表 append-only：数据库规则把 DELETE/UPDATE 变成空操作，
//     应用账号另需 REVOKE；
//   - 每条事件参与哈希链（event_hash = SHA256(规范化字段 ‖ prev_hash)）：
//     改一条会让其后所有哈希对不上，校验函数能精确定位断链点；
//   - **Canonical() 的字段集合与顺序一旦上线即冻结**——改动会使历史链
//     全部失效。需要新增字段时应发新版本的规范化函数并在 chain_root 上
//     标注版本，而不是就地修改；
//   - 签名密钥只经 CredentialRef 解析（ADR-014），绝不硬编码、不落库明文；
//   - 敏感字段的脱敏责任在调用方：本包提供 Redact 助手，但不代替调用方判断
//     什么是敏感的。
