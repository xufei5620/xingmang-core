// 铁律：
//   - HTTP 层只做协议转换与错误映射，**不做授权判定**——授权在 Action 内核，
//     前端隐藏按钮不构成安全控制（规格 §4.2）。在这里加权限短路等于制造
//     第二套规则，两套规则迟早会分叉；
//   - 对外错误只暴露稳定错误码与安全文案，绝不透传底层错误文本
//     （规格 §18.4）；根因只进服务端日志；
//   - 所有写操作经 Action 执行并返回 action_run_id（规格 §5.8）；
//   - 平台不参与用户实时请求路径（ADR-011）：本服务只服务管理后台与
//     后置的内部集成 API。
