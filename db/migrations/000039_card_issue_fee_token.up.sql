-- XM-CARD10：把开卡费的**计价代币**记下来。
--
-- 000030 落了 issue_fee_text（实测 1 USD 固定，产品负责人 2026-09-06 复述为
-- 「开卡费用是 1U」），但只有数字没有单位——而申请时用的是 USDT 还是 USDC
-- 是开卡请求的一个参数（token_type），我们本来就知道，只是没存。
--
-- 不存的后果不是「少一列」，是**成本汇总只能靠猜单位**：把一列 USDT 的开卡费
-- 直接加到一列 USD 的消费上，得出的数看起来完全正常，却是把两种资产当成了
-- 同一种。产品负责人 2026-09-06 明确选了「分币种列，不折算」，那就必须先
-- 知道每一笔是什么币种。
--
-- 已有的卡这一列为空 = **单位未记录**，页面如实说明，不回填成 USDT。
-- 1 USDT ≈ 1 USD 是一个汇率假设，不是事实；把假设写进历史数据，
-- 以后就再也分不清哪些是记录、哪些是我们替它填的。
ALTER TABLE cards.infini_card
    ADD COLUMN IF NOT EXISTS issue_fee_token text NOT NULL DEFAULT '';
